# Federated Learning Helper Functions

def get_model_weights(model):
    return model.get_weights()

def set_model_weights(model, weights):
    model.set_weights(weights)
    return model

def train_local_model(global_weights, X_local, y_local, epochs=1):
    local_model = build_cnn()
    set_model_weights(local_model, global_weights)
    local_model.fit(X_local, y_local,
                    epochs=epochs, batch_size=32, verbose=0)
    return get_model_weights(local_model)

def federated_average(global_weights, local_weights_list, dataset_sizes):
    total_samples   = sum(dataset_sizes)
    averaged_weights = []
    for layer_idx in range(len(global_weights)):
        layer_avg = np.zeros_like(global_weights[layer_idx])
        for local_weights, n in zip(local_weights_list, dataset_sizes):
            layer_avg += (n / total_samples) * local_weights[layer_idx]
        averaged_weights.append(layer_avg)
    return averaged_weights

def evaluate_model(weights, X_test, y_test):
    model = build_cnn()
    set_model_weights(model, weights)
    _, acc = model.evaluate(X_test, y_test, verbose=0)
    return acc

