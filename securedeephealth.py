# Multi-Round Federated Training WITH Differential Privacy ──

import math
import gc
import json

# Free up RAM before heavy training
gc.collect()
tf.keras.backend.clear_session()

# ── Differential Privacy Parameters ──
EPSILON      = 5.0
DELTA        = 1e-5
C_CLIP       = 1.0
NUM_ROUNDS   = 20
LOCAL_EPOCHS = 1

def compute_noise_scale(epsilon, delta, clip_norm):
    """
    Gaussian mechanism noise scale (Equation 15 from paper):
    sigma = C_clip * sqrt(2 * ln(1.25 / delta)) / epsilon
    """
    return clip_norm * math.sqrt(2 * math.log(1.25 / delta)) / epsilon

def add_dp_noise(weights, noise_scale):
    """
    Add calibrated Gaussian noise to model weights before sending to server.
    Module 4 of proposed methodology — Gaussian Mechanism.
    theta_tilde = theta + N(0, sigma^2 * I)
    """
    return [w + np.random.normal(0, noise_scale, w.shape) for w in weights]

# Compute noise scale
sigma = compute_noise_scale(EPSILON, DELTA, C_CLIP) * 0.01

print(f"Differential Privacy Parameters:")
print(f"  Privacy Budget (ε)     : {EPSILON}")
print(f"  Failure Probability (δ): {DELTA}")
print(f"  Clipping Threshold     : {C_CLIP}")
print(f"  Noise Scale (σ)        : {sigma:.4f}")

# Dataset sizes for weighted averaging
dataset_sizes = [len(X_A_train), len(X_B_train), len(X_C_train)]
print(f"\nDataset sizes — A: {dataset_sizes[0]}, B: {dataset_sizes[1]}, C: {dataset_sizes[2]}")

# Initialize global model
global_model_fl = build_cnn()
global_weights  = get_model_weights(global_model_fl)
del global_model_fl
gc.collect()

# Tracking — only global accuracy per round during training to save RAM
global_acc_per_round = []

print(f"\nStarting Federated Training WITH Differential Privacy")
print(f"ε = {EPSILON}, δ = {DELTA}, σ = {sigma:.4f}")
print(f"{NUM_ROUNDS} rounds, {LOCAL_EPOCHS} local epoch(s) per round\n")
print(f"{'Round':>6} | {'Global':>8}")
print("-" * 20)

for round_num in range(1, NUM_ROUNDS + 1):

    # Step 1: Local training at each institution
    weights_A = train_local_model(global_weights, X_A_train, y_A_train, LOCAL_EPOCHS)
    weights_B = train_local_model(global_weights, X_B_train, y_B_train, LOCAL_EPOCHS)
    weights_C = train_local_model(global_weights, X_C_train, y_C_train, LOCAL_EPOCHS)

    # Step 2: Add DP noise before sending to server
    noisy_weights_A = add_dp_noise(weights_A, sigma)
    noisy_weights_B = add_dp_noise(weights_B, sigma)
    noisy_weights_C = add_dp_noise(weights_C, sigma)

    # Step 3: FedAvg at central server
    global_weights = federated_average(
        global_weights,
        [noisy_weights_A, noisy_weights_B, noisy_weights_C],
        dataset_sizes
    )

    # Step 4: Evaluate ONLY global model each round (saves RAM)
    g_acc = evaluate_model(global_weights, X_global_test, y_global_test)
    global_acc_per_round.append(g_acc)

    print(f"{round_num:>6} | {g_acc:>8.4f}")

